package com.marketlens.backend;

import org.junit.jupiter.api.Test;

import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Prueba de regresión de restricciones para la migración V24.
 * H2 en modo PostgreSQL es una verificación de compatibilidad básica;
 * la migración definitiva se valida al ejecutar Flyway con PostgreSQL real.
 */
class TemuReferenceConstraintMigrationTest {

    @Test
    void temuProductIsAllowedWithoutChangingLegacyReferenceTypes() throws Exception {
        try (var connection = DriverManager.getConnection(
                "jdbc:h2:mem:temu_reference_constraints;MODE=PostgreSQL;DB_CLOSE_DELAY=-1",
                "sa", "");
             Statement statement = connection.createStatement()) {

            statement.execute("""
                    CREATE TABLE marketplace_references (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        marketplace VARCHAR(40) NOT NULL,
                        reference_type VARCHAR(40) NOT NULL,
                        external_id VARCHAR(120) NOT NULL,
                        CONSTRAINT chk_marketplace_reference_type
                            CHECK (reference_type IN ('LISTING','CATALOG_PRODUCT','USER_PRODUCT'))
                    )
                    """);
            statement.execute("""
                    CREATE TABLE publications (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        marketplace VARCHAR(50) NOT NULL,
                        reference_type VARCHAR(30),
                        CONSTRAINT chk_publication_reference_type
                            CHECK (reference_type IS NULL OR reference_type IN ('LISTING','USER_PRODUCT'))
                    )
                    """);

            // Comprobar que el estado anterior reproduce el defecto.
            assertThrows(SQLException.class, () -> statement.execute(
                    "INSERT INTO marketplace_references (marketplace, reference_type, external_id) "
                    + "VALUES ('TEMU','PRODUCT','606892013277333')"));
            assertThrows(SQLException.class, () -> statement.execute(
                    "INSERT INTO publications (marketplace, reference_type) VALUES ('TEMU','PRODUCT')"));

            String migration;
            try (InputStream source = getClass().getClassLoader().getResourceAsStream(
                    "db/migration/V24__enable_temu_product_references.sql")) {
                assertNotNull(source, "No se encontró la migración V24");
                migration = new String(source.readAllBytes(), StandardCharsets.UTF_8);
            }

            // Las instrucciones SQL de V24 no contienen puntos y coma dentro
            // de cadenas ni bloques especiales.
            migration = migration.replaceAll("(?m)^--.*$", "");
            for (String statementSql : migration.split(";")) {
                if (!statementSql.isBlank()) statement.execute(statementSql.trim());
            }

            assertDoesNotThrow(() -> statement.execute(
                    "INSERT INTO marketplace_references (marketplace, reference_type, external_id) "
                    + "VALUES ('TEMU','PRODUCT','606892013277333')"));
            assertDoesNotThrow(() -> statement.execute(
                    "INSERT INTO publications (marketplace, reference_type) VALUES ('TEMU','PRODUCT')"));

            // Mantener combinaciones anteriores válidas.
            assertDoesNotThrow(() -> statement.execute(
                    "INSERT INTO marketplace_references (marketplace, reference_type, external_id) "
                    + "VALUES ('MERCADO_LIBRE','USER_PRODUCT','MLAU12345678')"));
            assertDoesNotThrow(() -> statement.execute(
                    "INSERT INTO marketplace_references (marketplace, reference_type, external_id) "
                    + "VALUES ('MERCADO_LIBRE','CATALOG_PRODUCT','MLA12345678')"));
            assertDoesNotThrow(() -> statement.execute(
                    "INSERT INTO publications (marketplace, reference_type) VALUES ('FACEBOOK_MARKETPLACE','LISTING')"));

            // PRODUCT debe seguir siendo exclusivo de Temu.
            assertThrows(SQLException.class, () -> statement.execute(
                    "INSERT INTO marketplace_references (marketplace, reference_type, external_id) "
                    + "VALUES ('FACEBOOK_MARKETPLACE','PRODUCT','12345678')"));
            assertThrows(SQLException.class, () -> statement.execute(
                    "INSERT INTO publications (marketplace, reference_type) "
                    + "VALUES ('MERCADO_LIBRE','PRODUCT')"));
        }
    }
}
